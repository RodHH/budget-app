// End-to-end smoke test in a real browser at iPhone size. Usage: node scripts/smoke.mjs <baseUrl> <shotsDir>
import { chromium, devices } from 'playwright';
const [base = 'http://localhost:8080', shots = '.'] = process.argv.slice(2);
const browser = await chromium.launch();
const ctx = await browser.newContext({ ...devices['iPhone 13'], colorScheme: process.env.DARK ? 'dark' : 'light' });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
const shot = (n) => page.screenshot({ path: `${shots}/${n}.png`, fullPage: !!process.env.FULL });
await page.goto(base);
await page.waitForSelector('form');
if (await page.locator('text=Setup code').count()) {
  await page.fill('input[autocomplete=one-time-code]', 'TEST1234');
  await page.fill('input[autocomplete=username]', 'rodrigo');
  await page.fill('input[autocomplete=new-password] >> nth=0', 'a long test passphrase');
  await page.fill('input[autocomplete=new-password] >> nth=1', 'a long test passphrase');
  await shot('01-setup');
  await page.click('button:has-text("Create login")');
}
await page.waitForSelector('text=Your budget is empty');
await shot('02-empty');
await page.click('text=Try sample data');
await page.click('button:has-text("Add sample data")');
await page.waitForSelector('text=Remove sample data');
await page.goto(`${base}/#/dashboard`);
await page.waitForSelector('text=Left across all budgets');
await shot('03-dashboard');
await page.evaluate(() => window.scrollTo(0, 700));
await shot('04-dashboard-scrolled');
await page.goto(`${base}/#/transactions`);
await page.waitForSelector('.day-head');
await shot('05-activity');
await page.fill('input[type=search]', 'starbucks');
await page.waitForTimeout(500);
await shot('06-search');
await page.click('.item >> nth=0');
await page.waitForSelector('.sheet'); await page.waitForTimeout(400);
await shot('07-edit-txn');
await page.click('.sheet button:has-text("Cancel")');
await page.click('.fab');
await page.fill('.sheet .money-input input', '42.50');
await page.fill('.sheet input[placeholder="e.g. Trader Joe’s"]', 'Farmers market');
await page.selectOption('.sheet select >> nth=0', { label: '🛒 Groceries' });
await shot('08-new-txn');
await page.click('.sheet button:has-text("Save")');
await page.waitForSelector('.toast');
await page.goto(`${base}/#/budgets`);
await page.waitForSelector('text=Left this period');
await shot('09-budgets');
await page.click('.item:has-text("Coffee")');
await page.waitForSelector('.sheet'); await page.waitForTimeout(400);
await shot('10-edit-budget');
await page.click('.sheet button:has-text("Cancel")');
await page.goto(`${base}/#/accounts`);
await page.waitForSelector('text=Bank connections');
await shot('11-accounts');
await page.goto(`${base}/#/more?section=alerts`);
await page.waitForSelector('text=Thresholds');
await shot('12-alerts');
await page.goto(`${base}/#/more?section=setup`);
await page.waitForSelector('text=Setup status');
await shot('13-setup');
await page.goto(`${base}/#/more?section=rules`);
await page.waitForSelector('text=Rules run in order');
await shot('14-rules');
console.log(errors.length ? `ERRORS:\n${errors.join('\n')}` : 'no browser errors');
await browser.close();
